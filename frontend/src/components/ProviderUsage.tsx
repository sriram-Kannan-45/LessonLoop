import type { Attempt, Usage } from '../lib/workspace'

function label(usage: Usage) { return `${usage.provider} · ${usage.model}` }

export function ProviderUsage({ attempt }: { attempt: Attempt }) {
  const generation = attempt.generation_usage || {}
  const evaluation = attempt.evaluator_usage || {}
  const groups = evaluation.group_usage || (evaluation.provider ? [evaluation] : [])
  const judges = [...new Set(groups.filter(item => item.provider && item.model).map(label))]
  const fallback = generation.fallback || groups.some(item => item.fallback)
  if (!generation.provider && !judges.length) return null
  return <div className="provider-trace" aria-label={`Actual providers for draft ${attempt.number}`}>
    {fallback && <strong>Groq quota fallback used</strong>}
    {generation.provider && <p>Generated by <span>{label(generation)}</span></p>}
    {judges.length > 0 && <p>Evaluated by <span>{judges.join('; ')}</span></p>}
  </div>
}
